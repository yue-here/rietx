def _source_ref() -> str:
    """The git ref this build's file links name (`sphinx_shared.SOURCE_REF`).

    The tests load this file by path, so its sibling is not importable until
    its directory is on the path.
    """
    here = str(_Path(__file__).resolve().parent)
    if here not in _sys.path:
        _sys.path.append(here)
    from sphinx_shared import SOURCE_REF
    return SOURCE_REF

