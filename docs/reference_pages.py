# The plan ladder
#
# Drawn from the plan objects, because the old tree's hand-drawn diagram
# drifted once: it left out the `extra_components` stage that
# `mccusker_structural` runs sixth of eleven.
# ----------------------------------------------------------------------

def _stage_defaults() -> dict:
    from rietx.strategy.staged import Stage

    return {f.name: f.default for f in _dataclasses.fields(Stage)
            if f.default is not _dataclasses.MISSING}


def _stage_label(stage, defaults: dict) -> str:
    lines = [stage.name, *stage.turn_on]
    lines += [f"{name} = {getattr(stage, name)}" for name, default in defaults.items()
              if getattr(stage, name) != default]
    # Mermaid 11 reads `*` as markdown emphasis, and decodes `#42;` before it
    # does, so only a backslash keeps a glob's stars (measured on 11.12.1).
    return "<br>".join(line.replace('"', "#quot;").replace("*", "\\*") for line in lines)


def _ladder(plan) -> list[str]:
    defaults = _stage_defaults()
    out = ["```{mermaid}", "flowchart TB"]
    for i, stage in enumerate(plan.stages):
        out.append(f'  s{i}["{_stage_label(stage, defaults)}"]')
    if len(plan.stages) > 1:
        out.append("  " + " --> ".join(f"s{i}" for i in range(len(plan.stages))))
    return out + ["```", ""]


def _ftol_sentence(ftol: float | None) -> str:
    if ftol is None:
        return "Every stage runs to the solver's own tolerance."
    return (f"Every stage before the last stops at `ftol = {ftol:g}`. "
            "The last runs to the solver's own tolerance.")


def plan_ladder() -> str:
    """The body of `reference/plans.md`: a summary table, then one ladder per preset."""
    from rietx.strategy.staged import _MODE_SUBSTITUTES, PLAN_INFO, PLAN_PRESETS

    plans = {name: build() for name, build in PLAN_PRESETS.items()}
    out = [_BANNER.format(source="PLAN_PRESETS and PLAN_INFO"), "",
           "| Preset | Title | Modes | Stages |", "| --- | --- | --- | --- |"]
    for name, plan in plans.items():
        info = PLAN_INFO[name]
        modes = ", ".join(f"`{m}`" for m in info.modes)
        out.append(f"| [`{name}`](#{name}) | {_cell(info.title)} | {modes} "
                   f"| {len(plan.stages)} |")
    out.append("")
    for (name, mode), twin in _MODE_SUBSTITUTES.items():
        out.append(f"Under `{mode}`, `{name}` runs as `{twin}`.")
    ftols = {plan.intermediate_ftol for plan in plans.values()}
    shared = len(ftols) == 1
    if shared:
        out.append(_ftol_sentence(next(iter(ftols))))
    out.append("")
    for name, plan in plans.items():
        info = PLAN_INFO[name]
        out += [f"## `{name}`", "", info.description, "", info.when_to_use, ""]
        if not shared:
            out += [_ftol_sentence(plan.intermediate_ftol), ""]
        out += _ladder(plan)
    return "\n".join(out)


# ----------------------------------------------------------------------
# The diagnostic index
#
# There is no registry of codes, so the index walks the source.  A code is an
# UPPER_SNAKE literal in one of three places: a `code=` keyword (every
# `Diagnostic(...)`), the first argument of a `GuardFinding` constructor, or a
# module-level `*_CODES` table.  `tests/skill_surface.py` walks the first
# shape for the skill, and a test holds this walk to a superset of it.  The GUI
# server's session codes share the shape and are a separate namespace, so
# `gui/` is skipped, as the skill skips it.
# ----------------------------------------------------------------------

_CODE_SHAPE = _re.compile(r"[A-Z][A-Z0-9_]+")
_LEVELS = {"info", "warning", "error"}
SOURCE_ROOT = _Path(__file__).resolve().parent.parent / "src" / "rietx"


def _code_literals(node) -> set[str]:
    return {n.value for n in _ast.walk(node) if isinstance(n, _ast.Constant)
            and isinstance(n.value, str) and _CODE_SHAPE.fullmatch(n.value)}


def diagnostic_index(root: _Path = SOURCE_ROOT) -> dict[str, dict[str, set[str]]]:
    """Code -> {"levels": the literal `level=` values beside it, "files": where}.

    A level computed at run time is recorded as "".  A `*_CODES` table often
    lists codes raised elsewhere, to filter or cap them, so a table names a
    code's file only when nothing else in the tree does.
    """
    out: dict[str, dict[str, set[str]]] = {}
    tabled: dict[str, set[str]] = {}

    def add(code: str, rel: str, level: str | None) -> None:
        entry = out.setdefault(code, {"levels": set(), "files": set()})
        entry["files"].add(rel)
        if level is not None:
            entry["levels"].add(level)

    for path in sorted(root.rglob("*.py")):
        rel = path.relative_to(root.parent).as_posix()
        if "gui" in rel.split("/")[1:]:
            continue
        tree = _ast.parse(path.read_text(encoding="utf-8"), filename=rel)
        for node in tree.body:
            targets = (node.targets if isinstance(node, _ast.Assign)
                       else [node.target] if isinstance(node, _ast.AnnAssign) and node.value
                       else [])
            if any(isinstance(t, _ast.Name) and t.id.endswith("_CODES") for t in targets):
                for code in _code_literals(node.value):
                    tabled.setdefault(code, set()).add(rel)
        for node in _ast.walk(tree):
            if not isinstance(node, _ast.Call):
                continue
            keywords = {k.arg: k.value for k in node.keywords}
            code = keywords.get("code")
            if (isinstance(code, _ast.Constant) and isinstance(code.value, str)
                    and _CODE_SHAPE.fullmatch(code.value)):
                level = keywords.get("level")
                add(code.value, rel, level.value if isinstance(level, _ast.Constant)
                    else "" if level is not None else None)
            callee = node.func
            name = callee.id if isinstance(callee, _ast.Name) else getattr(callee, "attr", "")
            if name in {"cls", "GuardFinding"} and node.args:
                for literal in _code_literals(node.args[0]):
                    add(literal, rel, None)
            # a helper taking (level, code) positionally, `_note(d, "info", "CODE", ...)`
            plain = [a.value for a in node.args
                     if isinstance(a, _ast.Constant) and isinstance(a.value, str)]
            levels = [s for s in plain if s in _LEVELS]
            if len(levels) == 1:
                for literal in plain:
                    if _CODE_SHAPE.fullmatch(literal) and "_" in literal:
                        add(literal, rel, levels[0])
    for code, files in tabled.items():
        if code not in out:
            for rel in files:
                add(code, rel, None)
    return out


#: The diagnostic pages: (page stem, title, the source areas it takes).  One
#: page of every code passed the page contract's 50 000-character cap once each
#: code carried its explanation, so codes are filed by where they are raised.
#: The first area prefix a code's first file matches decides; "" takes the rest.
DIAGNOSTIC_GROUPS = (
    ("diagnostics-projects", "Other programs' projects", ("rietx/io/projects/",)),
    ("diagnostics-files", "Reading files", ("rietx/io/",)),
    ("diagnostics-indexing", "Peaks and indexing", ("rietx/indexing/",)),
    # not `rietx/schemas/`: the codes raised there are a result's capped
    # correlation counts and a stored file's migrated ranges, not structure
    ("diagnostics-structures", "Structures and magnetism",
     ("rietx/crystallography/", "rietx/strategy/magnetic",
      "rietx/report/magnetic")),
    ("diagnostics-series", "Series and joint fits", ("rietx/sequential", "rietx/multi")),
    ("diagnostics-refinement", "Refinement", ("",)),
)


def diagnostic_group(files: set[str]) -> str:
    """The page stem a code with these raising files is listed on."""
    first = sorted(files)[0]
    return next(stem for stem, _title, areas in DIAGNOSTIC_GROUPS
                if any(first.startswith(area) for area in areas))


def _levels(entry: dict[str, set[str]]) -> str:
    levels = sorted(lv for lv in entry["levels"] if lv)
    if "" in entry["levels"]:
        levels.append("set at run time")
    return ", ".join(levels) or "set by a helper"


def diagnostic_page() -> str:
    """The body of `reference/diagnostics.md`: every code, its name and its page."""
    from rietx.help import explain

    index = diagnostic_index()
    titles = {stem: title for stem, title, _areas in DIAGNOSTIC_GROUPS}
    out = [_BANNER.format(source="the source tree under src/rietx/"), "",
           f"The package raises {len(index)} codes.", "",
           "| Code | Name | Page |", "| --- | --- | --- |"]
    for code in sorted(index):
        stem = diagnostic_group(index[code]["files"])
        entry = explain(code)
        name = "" if entry is None else entry.title
        out.append(f"| [`{code}`]({stem}.md#{code.lower()}) "
                   f"| {name} | {titles[stem]} |")
    return "\n".join(out + [""])


def diagnostic_group_page(stem: str) -> str:
    """The body of `reference/<stem>.md`: one section per code on that page.

    Each section carries the code's explanation from `rietx.help.DIAGNOSTIC_HELP`,
    so the page and a notebook's folded explanation are one text, and a heading
    per code gives every code a link target.
    """
    from rietx._about import REPO_URL
    from rietx.help import explain

    ref = _source_ref()
    index = diagnostic_index()
    codes = [c for c in sorted(index) if diagnostic_group(index[c]["files"]) == stem]
    out = [_BANNER.format(source="the source tree under src/rietx/"), ""]
    for code in codes:
        files = ", ".join(f"[`{rel}`]({REPO_URL}/blob/{ref}/src/{rel})"
                          for rel in sorted(index[code]["files"]))
        out += [f"## `{code}`", ""]
        help_entry = explain(code)
        if help_entry is not None:
            out += [f"{help_entry.title}.", "", help_entry.description, ""]
        out += [f"Level: {_levels(index[code])}. Raised in {files}.", ""]
    return "\n".join(out)


