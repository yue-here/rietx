def _constant(module: str, name: str) -> str:
    import importlib

    return getattr(importlib.import_module(module), name)


def _tree_lines(entries: list[tuple[str, list]], prefix: str = "") -> list[str]:
    lines = []
    for i, (name, children) in enumerate(entries):
        last = i == len(entries) - 1
        lines.append(f"{prefix}{'└── ' if last else '├── '}{name}")
        lines += _tree_lines(children, prefix + ("    " if last else "│   "))
    return lines


def project_tree() -> str:
    """The body of `reference/project.md`: the tree, then what each entry holds."""
    import tempfile

    from rietx.examples import build_example
    from rietx.gui.session import EXPORT_DEFAULTS
    from rietx.runs import RUN_ID_RE

    if not RUN_ID_RE.match(EXAMPLE_RUN_ID):
        raise RuntimeError(f"EXAMPLE_RUN_ID {EXAMPLE_RUN_ID!r} no longer matches runs.RUN_ID_RE")
    with tempfile.TemporaryDirectory() as tmp:
        project = build_example("fap", tmp)
        created = {p.relative_to(project.path).as_posix() for p in project.path.rglob("*")}
        name, pattern = project.path.name, project.data_ref.filename

    named = {_constant(m, c): (m, c, what) for m, c, what in PROJECT_ENTRIES}
    unnamed = sorted(created - set(named) - {pattern})
    if unnamed:
        raise RuntimeError(f"a new project has entries no row of PROJECT_ENTRIES names: {unnamed}")

    live, exports = _constant("rietx.project", "LIVE_DIR"), _constant("rietx.project", "EXPORTS_DIR")
    gitignore = _constant("rietx.runs", "GITIGNORE_FILE")
    per_run = [(_constant(m, c), []) for m, c, _ in RUN_ENTRIES if c != "GITIGNORE_FILE"]
    children = {
        live: [(gitignore, []), (f"{EXAMPLE_RUN_ID}/", per_run)],
        exports: [(f, []) for f in EXPORT_DEFAULTS.values()],
    }

    def shown(entry: str) -> str:
        return f"{entry}/" if entry in children else entry

    # The pattern file sits beside project.json, whatever order the rows take.
    entries = []
    for m, c, _ in PROJECT_ENTRIES:
        entries.append(_constant(m, c))
        if c == "PROJECT_JSON":
            entries.append(pattern)
    root = [(shown(e), children.get(e, [])) for e in entries]
    at_creation = [f"`{shown(e)}`" for e in entries if e in created]
    empty = [f"`{d}/`" for d in (live, exports)
             if d in created and not any(p.startswith(f"{d}/") for p in created)]

    def listed(items: list[str]) -> str:
        return " and ".join(filter(None, [", ".join(items[:-1]), items[-1]])) if items else ""

    starts_empty = (f"{listed(empty)} {'starts' if len(empty) == 1 else 'start'} empty. "
                    if empty else "")
    out = [_BANNER.format(source="a project rietx.examples builds"), "",
           "```text", f"{name}/", *_tree_lines(root), "```", "",
           f"A new project holds {listed(at_creation)}. "
           + starts_empty + "A fit, the GUI or an export writes everything else.", "",
           "| Entry | Named by | What it holds |", "| --- | --- | --- |",
           f"| `{pattern}` | `DataRef.filename` | The pattern file, copied byte for byte. |"]
    for module, constant, what in PROJECT_ENTRIES:
        out.append(f"| `{shown(_constant(module, constant))}` | `{module}.{constant}` | {what} |")
    for module, constant, what in RUN_ENTRIES:
        where = f"{live}/" if constant == "GITIGNORE_FILE" else f"{live}/<run id>/"
        out.append(f"| `{where}{_constant(module, constant)}` | `{module}.{constant}` | {what} |")
    out.append(f"| `{exports}/…` | `rietx.gui.session.EXPORT_DEFAULTS` "
               "| One file per export kind, under these default names. |")
    return "\n".join(out + [""])


# ----------------------------------------------------------------------
# The roadmap
#
# Read from `docs/ROADMAP.md`'s milestone table, which is the planning set's
# own authority.  A numbered release is a cut, not a direction, so only the
# named milestones and the fence are shown.  A scope cell is cut at its first
# " — ", after which the table speaks to maintainers (WP links, issue numbers),
# and a "(was vX.Y)" note about an old number is dropped.
# ----------------------------------------------------------------------

DOCS_ROOT = _Path(__file__).resolve().parent
_MD_LINK = _re.compile(r"\[([^\]]*)\]\(([^)]*)\)")


def _milestone_rows(roadmap: str) -> list[dict[str, str]]:
    section = _re.split(r"^## Milestones$", roadmap, maxsplit=1, flags=_re.M)[1]
    section = _re.split(r"^## ", section, maxsplit=1, flags=_re.M)[0]
    rows = []
    for line in section.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != 4 or cells[0] in {"Milestone", ""} or set(cells[0]) <= {"-"}:
            continue
        name, scope, status, _ = cells
        if status.startswith("✅") or _re.fullmatch(r"v\d+\.\d+", name):
            continue
        record = next((url for _, url in _MD_LINK.findall(status)
                       if url.startswith("milestones/")), None)
        rows.append({
            "name": name,
            "scope": _re.sub(r"\s*\(was v[\d.]+\)", "", scope.split(" — ")[0]),
            "status": _MD_LINK.sub("", status).replace("**", "").strip(" ()⬜🔄"),
            "record": record,
        })
    return rows


def roadmap_page() -> str:
    """The body of `switching/roadmap.md`."""
    from rietx import __version__
    from rietx._about import REPO_URL

    ref = _source_ref()
    rows = _milestone_rows((DOCS_ROOT / "ROADMAP.md").read_text(encoding="utf-8"))
    if "dev" in __version__:
        # 1.10.0.dev0 is 1.10's build, and 1.9.1.dev0 is 1.9.1's, not 1.9's.
        release = _re.sub(r"\.0$", "", __version__.split(".dev")[0])
        built = (f"This manual was built from {__version__}, "
                 f"a development build of the next release, {release}.")
    else:
        built = f"This manual was built from release {__version__}."
    out = [_BANNER.format(source="docs/ROADMAP.md"), "", built, "",
           "| Milestone | Scope | Status |", "| --- | --- | --- |"]
    for row in rows:
        status = row["status"]
        if row["record"]:
            status += f" ([record]({REPO_URL}/blob/{ref}/docs/{row['record']}))"
        out.append(f"| {row['name']} | {_cell(row['scope'])} | {status} |")
    return "\n".join(out + [""])


# ----------------------------------------------------------------------
# The API reference
#
# Grouped by how likely each call is to be used, and the grouping is not
# authored here.  The skill's index generator (`docs/skill/make_api_index.py`)
# already decides it: `SECTIONS` is what every session calling rietx needs,
# `TECHNIQUES` what a session doing one technique needs, and every other name
# in `rietx.__all__` is the third tier.  The skill's section paragraphs are
# written to an agent and are left out.
#
# Each name is a Sphinx Python-domain object (WP-2022), so the theme draws its
# signature a parameter a line with names, annotations and defaults told
# apart, and the object gets a permalink, a contents entry and a search entry.
# The text inside each directive comes from that script's own builders
# (`_signature`, `_doc_line`, the field parts), so a signature here and in the
# skill cannot differ.  Not autodoc, which would render whole docstrings,
# written in the rulebook register (WP-1981).
#
# This page does not count as documenting a name: `tests/test_manual_api.py`
# skips `_generated/`, so its coverage partition still asks for prose.
# ----------------------------------------------------------------------

@_functools.cache
def _api_index():
    import importlib.util

    spec = importlib.util.spec_from_file_location(
        "_make_api_index", DOCS_ROOT / "skill" / "make_api_index.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _directive(kind: str, argument: str, body: str, *, options: dict[str, str] | None = None,
               children: list[str] = (), no_index: bool = False) -> str:
    """One `py:<kind>` directive as a MyST fence, children nested inside it.

    A name described twice fails a `-W` build ("duplicate object description"),
    so a repeat carries `:no-index:`: it still renders, and links go to the first.
    """
    options = dict(options or {})
    if no_index:
        options["no-index"] = ""
    fence = "````" if children else "```"
    lines = [f"{fence}{{py:{kind}}} {argument}".rstrip()]
    lines += [f":{key}: {value}".rstrip() for key, value in options.items()]
    if body:
        lines += [body]
    for child in children:
        lines += ["", child.rstrip("\n")]
    lines.append(fence)
    return "\n".join(lines) + "\n"


def _api_entry(index, dotted: str, technique: str | None = None, *,
               no_index: bool = False) -> str:
    """One name as a Python-domain object: its signature, its summary line
    and, for a model or a dataclass, its fields in one `py:fields`."""
    import inspect

    from pydantic import BaseModel

    obj = index._resolve(dotted)
    module, name = _api_module(dotted)
    # The module is the object's own, so a contents entry reads `Refinement.summary()`
    # where the bare name would be one of several `summary()`s.
    options = {"module": module}
    if inspect.isclass(obj) and issubclass(obj, BaseException):
        doc = f"An exception. {_notation(index._doc_line(obj))}".rstrip()
        return _directive("exception", name, doc, options=options, no_index=no_index)
    if isinstance(obj, dict):
        keys = ", ".join(f"`{k}`" for k in obj)
        return _directive("data", name, f"A dict. Keys: {keys}.", options=options,
                          no_index=no_index)
    if not (inspect.isclass(obj) or callable(obj)):
        return _directive("data", name, "A constant.", options={**options, "value": repr(obj)},
                          no_index=no_index)
    doc = _notation(index._doc_line(obj))
    if inspect.isclass(obj) and (issubclass(obj, BaseModel) or _dataclasses.is_dataclass(obj)):
        if issubclass(obj, BaseModel):
            skip = (index.TECHNIQUE_FIELDS.get(dotted, frozenset()) if technique is None
                    else frozenset())
            parts = index.model_field_parts(obj, skip)
        else:
            parts = index.dataclass_field_parts(obj)
        # `py:fields` (docs/py_fields.py): one signature line a field.
        lines = [f"{field}: {ann}" + (f" = {default}" if default is not None else "")
                 for field, ann, default in parts]
        fields = [_directive("fields", "", "\n".join(lines), no_index=no_index)] if parts else []
        return _directive("class", name, doc, options=options, children=fields,
                          no_index=no_index)
    if inspect.isclass(obj):
        return _directive("class", name + index._signature(obj, drop_self=False), doc,
                          options=options, no_index=no_index)
    owner, _, attr = dotted.rpartition(".")
    owner = index._resolve(owner) if "." in dotted[3:] else None
    if not inspect.isclass(owner):
        return _directive("function", name + index._signature(obj, drop_self=False), doc,
                          options=options, no_index=no_index)
    # Called on the class, so it says so: `Structure.from_cif`, `Project.open`.
    kind = inspect.getattr_static(owner, attr)
    if isinstance(kind, classmethod):
        options["classmethod"] = ""
    elif isinstance(kind, staticmethod):
        options["staticmethod"] = ""
    return _directive("method", name + index._signature(obj, drop_self=True), doc,
                      options=options, no_index=no_index)


def _api_module(dotted: str) -> tuple[str, str]:
    """(module, name within it): `rx` for a name reached as `rx.`, else the
    longest importable prefix, as `make_api_index._resolve` walks it."""
    import importlib

    if dotted.startswith("rx."):
        return "rx", dotted[3:]
    parts = dotted.split(".")
    for n in range(len(parts) - 1, 0, -1):
        try:
            importlib.import_module(".".join(parts[:n]))
        except ModuleNotFoundError:
            continue
        return ".".join(parts[:n]), ".".join(parts[n:])
    raise ValueError(f"{dotted}: no importable module prefix")


def api_tiers() -> list[tuple[str, list[tuple[str, list[str]]], str | None]]:
    """(tier heading, [(section title, dotted names)], technique key) in reading order."""
    import rietx

    index = _api_index()
    everyday = [(title, list(names)) for title, _, names in index.SECTIONS]
    techniques = []
    for key, (title, _, sections) in index.TECHNIQUES.items():
        techniques.append((title, [(t, list(names)) for t, _, names in sections], key))
    placed = {name.split(".")[1] for _, sections in [("", everyday)] + [(t, s) for t, s, _ in techniques]
              for _, names in sections for name in names if name.startswith("rx.")}
    rest = sorted(set(rietx.__all__) - placed, key=str.lower)
    return ([("Everyday calls", everyday, None)]
            + [(title, sections, key) for title, sections, key in techniques]
            + [("Everything else in rx", [("", [f"rx.{name}" for name in rest])], None)])


def _api_body(start: int, stop: int | None) -> str:
    """The tiers `api_tiers()[start:stop]`.  A name an earlier tier, or an
    earlier section here, already described is a repeat (`_directive`)."""
    index = _api_index()
    every = api_tiers()
    seen = {name for _, sections, _ in every[:start] for _, names in sections for name in names}
    tiers = every[start:stop]
    out = [_BANNER.format(source="docs/skill/make_api_index.py's selection and rietx.__all__"), ""]
    # One tier is the page itself, so its sections take the H2 level.
    level = "##" if len(tiers) == 1 else "###"
    for heading, sections, technique in tiers:
        if len(tiers) > 1:
            out += [f"## {heading}", ""]
        for title, names in sections:
            if title:
                out += [f"{level} {title}", ""]
            for name in names:
                out += [_api_entry(index, name, technique, no_index=name in seen)]
                seen.add(name)
            out.append("")
    return "\n".join(out)


def api_everyday() -> str:
    """The body of `reference/api.md`: the calls a session making a fit needs."""
    return _api_body(0, 1)


def api_techniques() -> str:
    """The body of `reference/api-techniques.md`: one tier per technique."""
    return _api_body(1, -1)


def api_everything_else() -> str:
    """The body of `reference/api-types.md`: the rest of `rietx.__all__`."""
    return _api_body(-1, None)


