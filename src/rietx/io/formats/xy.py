#: A comment line that **states the x-axis unit**.  Mantid's own spelling is
#: ``The X-axis unit is: Time-of-flight``; the looser ``X unit = …`` costs
#: nothing and is what a hand-edited export tends to keep.  The word ``axis`` or
#: ``unit`` is *required* and the ``x`` must start a word, which is what keeps
#: this from matching a comment that merely ends in a colon — ``# Max: 90``
#: otherwise reads as a stated x-axis unit of "90" and earns the file a
#: spurious ``PATTERN_X_AXIS_ASSUMED``.  The comment marker is already stripped
#: by the caller.
_UNIT_RE = re.compile(
    r"\bx[-\s]?(?:axis\s*(?:units?)?|units?)\s*(?:is)?\s*[:=]\s*(\S.*?)\s*$",
    re.I)

#: What a stated unit has to contain to *be* a flight time.  ``tof`` is matched
#: as a whole word only: it is a substring of nothing here, but it is a
#: substring of plenty elsewhere and the boundary is what keeps this a
#: declaration rather than a search.
_TOF_UNIT_RE = re.compile(
    r"time[-\s]?of[-\s]?flight|\btof\b|microsecond|\bus\b|\bµs\b|\busec\b", re.I)

#: …and to be an angle.  ``d`` and ``q`` are deliberately absent: a d-spacing or
#: a Q column is neither of this package's two axes, so it falls to
#: :func:`check_axis`'s refusal arm rather than being classified here.
_ANGLE_UNIT_RE = re.compile(
    r"2[-\s]?theta|two[-\s]?theta|2θ|\bdegree|\bdeg\b|\bangle\b", re.I)

#: Units that are **recognisably something else** — the policy's refusal arm.
#: These are Mantid's own Unit Factory names, because Mantid is what writes this
#: header, and a bank exported in any of them parses perfectly and refines to a
#: cell that is wrong by a geometry rather than by a tolerance.  Matched on the
#: stated unit only, never on the file's numbers.
_OTHER_UNITS: tuple[tuple[re.Pattern[str], str], ...] = (
    (re.compile(r"d[-\s]?spacing", re.I), "a d-spacing in Å"),
    (re.compile(r"momentum\s*transfer|^q$|\bq\s*\(", re.I),
     "a momentum transfer Q in Å⁻¹"),
    (re.compile(r"q\s*squared", re.I), "a Q² in Å⁻²"),
    (re.compile(r"wavelength", re.I), "a wavelength in Å"),
    (re.compile(r"\benergy\b|\bdeltae\b|wavenumber", re.I),
     "a neutron energy"),
    (re.compile(r"\bmomentum\b", re.I), "a neutron momentum in Å⁻¹"),
)

#: A TOF-looking token anywhere in a comment, used **only** to decide whether
#: an assumed 2θ axis is worth a diagnostic.  Never to set the axis.
_TOF_HINT_RE = re.compile(r"time[-\s]?of[-\s]?flight|\btof\b", re.I)

_COMMENT_MARKERS = ("#", "!", "'", "/")


def _stated_axis(comments: list[str]
                 ) -> tuple[AxisKind | None, str | None, str | None]:
    """``(axis, stated, other)`` from the comment block — the file's declaration.

    The three-way policy's own three answers.  ``axis`` is the quantity when the
    file states one this reader can hold; ``other`` is what the axis *is* when
    it states one it cannot (a d-spacing, a Q), for :func:`check_axis`'s
    refusal; both ``None`` is "states nothing recognisable", which is the
    ordinary case for a format with no spec and is not an error.  ``stated`` is
    the unit verbatim in every case, for the metadata and for a message that has
    to quote it.
    """
    for line in comments:
        m = _UNIT_RE.search(line)
        if not m:
            continue
        stated = m.group(1)
        if _TOF_UNIT_RE.search(stated):
            return "tof", stated, None
        if _ANGLE_UNIT_RE.search(stated):
            return "two_theta", stated, None
        for pattern, what in _OTHER_UNITS:
            if pattern.search(stated):
                return None, stated, what
        return None, stated, None
    return None, None, None


#: How many lines an ``XYDATA`` file's heading takes, the keyword line included
#: (the FullProf manual, PDF p. 74: the keyword, then five heading lines).
_XYDATA_HEADING_LINES = 6


def _xydata_heading(lines: list[str], path: Path) -> float | None:
    """The sample temperature an ``XYDATA`` heading states, refusing what changes the numbers.

    ``lines`` are the five heading lines after the keyword.  ``INTER fac_x
    fac_y Interpol`` with a multiplier other than 1 means FullProf scales the
    x values, or y and σ, before it uses them; ``Interpol = 1`` means it
    interpolates them to a constant step.  Neither is applied here, so either
    is refused, naming the file and the value, rather than read as written.
    Returns ``tsamp`` from ``TEMP tsamp``, or ``None`` where the heading has
    no ``TEMP`` line, a value that is not a number, or one that is not
    positive (a file recording zero records nothing).
    """
    temperature = None
    for line in lines:
        parts = line.split()
        if not parts:
            continue
        key, values = parts[0].upper(), parts[1:]
        if key == "INTER":
            try:
                fac_x, fac_y = (float(v) for v in values[:2])
            except ValueError:
                raise ValueError(
                    f"{path}: the XYDATA heading's INTER line {line.strip()!r} "
                    f"does not start with two numbers (fac_x, fac_y)") from None
            interpol = values[2] if len(values) > 2 else "0"
            if fac_x != 1.0 or fac_y != 1.0:
                raise ValueError(
                    f"{path}: the XYDATA heading states INTER multipliers "
                    f"fac_x = {fac_x:g}, fac_y = {fac_y:g}. FullProf multiplies "
                    f"the x values by fac_x and y and σ by fac_y before using "
                    f"them, and this reader does not, so the file is refused "
                    f"rather than read with every value off by that factor. "
                    f"Re-export it with the factors applied and INTER 1 1.")
            if interpol.strip() == "1":
                raise ValueError(
                    f"{path}: the XYDATA heading states Interpol = 1, which "
                    f"tells FullProf to interpolate the data to a constant "
                    f"step. This reader reads the points as measured and does "
                    f"not interpolate, so the file is refused rather than read "
                    f"as a different pattern from FullProf's.")
        elif key == "TEMP" and values:
            try:
                value = float(values[0])
            except ValueError:
                continue
            temperature = value if value > 0.0 else None
    return temperature


def read_xy(path: str | Path, *,
            diagnostics: list[Diagnostic] | None = None) -> PatternData:
    """Rows of ``x y [σ]``, read by position; x is 2θ unless the file states a flight time.

    **A row is data only if it has the file's usual column count** (issue
    #266).  A header line that starts with a digit parses on its first three
    tokens: PDFgetX2's detector table put a point at (0, 1) on every file one
    reporter had.  So each row keeps its token count, the most common count
    is the file's, and a row with any other is dropped and reported as
    ``PATTERN_ROWS_DROPPED``.  A tie goes to the count of the last row,
    because a header sits above its data.  A header row with the data's own
    count is out of this check's reach; the axis check in ``read_pattern``
    still sees one landing at or below 0°.
    """
    p = Path(path)
    rows: list[tuple[int, list[str], list[float]]] = []
    comments: list[str] = []
    # the mark decides the codec, so a UTF-16 export from Windows vendor
    # software reads instead of dying on "no numeric data found"
    text = p.read_text(encoding=head(p).encoding, errors="replace")
    lines = text.splitlines()
    heading = 0
    temperature = None
    if lines and lines[0].lstrip("\ufeff").startswith("XYDATA"):
        heading = _XYDATA_HEADING_LINES
        temperature = _xydata_heading(lines[1:heading], p)
    for n, line in enumerate(lines, 1):
        if n <= heading:
            continue
        s = line.strip()
        if not s:
            continue
        if s.startswith(_COMMENT_MARKERS):
            comments.append(s.lstrip("".join(_COMMENT_MARKERS)).strip())
            continue
        parts = s.replace(",", " ").split()
        try:
            vals = [float(v) for v in parts[:3]]
        except ValueError:
            continue
        if len(vals) >= 2:
            rows.append((n, parts, vals))
    if not rows:
        raise ValueError(f"no numeric data found in {p}")
    counts = Counter(len(parts) for _, parts, _ in rows)
    arity = max(counts, key=lambda k: (counts[k], k == len(rows[-1][1])))
    dropped = [(n, parts) for n, parts, _ in rows if len(parts) != arity]
    if dropped and diagnostics is not None:
        shown = "; ".join(f"line {n}: {' '.join(parts)!r}"
                          for n, parts in dropped[:3])
        more = f", and {len(dropped) - 3} more" if len(dropped) > 3 else ""
        diagnostics.append(Diagnostic(
            level="warning", code="PATTERN_ROWS_DROPPED",
            message=(
                f"{p.name}: {len(dropped)} numeric row(s) have a column count "
                f"other than the file's {arity} and were not read as data "
                f"({shown}{more})."),
            where=[f"line {n}" for n, _ in dropped],
            suggestion=(
                "Re-export the file with one column count on every row if a "
                "dropped row is a measured point."),
            value=float(len(dropped)),
        ))
    # one column count, so every kept row parsed the same number of values
    arr = np.array([vals for _, parts, vals in rows if len(parts) == arity],
                   dtype=np.float64)
    n_cols = arr.shape[1]
    sigma = arr[:, 2] if n_cols >= 3 and np.any(arr[:, 2] > 0) else None

    axis, stated, other = _stated_axis(comments)
    if axis is None:
        # No recognised declaration: the axis is *assumed*, which is the third
        # row of the policy and the one that has to speak.  ``note`` carries the
        # TOF hint when there is one — a file that mentions a flight time
        # somewhere and states no unit is exactly the file whose reader should
        # not be silent, and exactly the file whose reader must not guess.
        hint = next((c for c in comments if _TOF_HINT_RE.search(c)), None)
        note = ("" if hint is None else
                f" This file's comments mention a flight time "
                f"({hint!r}) but state no x-axis unit. Export it with Mantid's "
                f"header line (\"The X-axis unit is: Time-of-flight\") to "
                f"read it as TOF.")
        check_axis(stated or "", path=p, field="x-axis unit",
                   two_theta=False, other=other, note=note,
                   remedy=("Export the bank in time-of-flight or in 2θ: those "
                           "are the two abscissae PatternData holds."),
                   diagnostics=diagnostics if (stated or hint) else None)
        axis = "two_theta"
    x, y, sig = ascending(arr[:, 0], arr[:, 1], sigma, path=p, fmt=XY,
                          axis=axis, diagnostics=diagnostics)
    return pattern_data(p, x, y, sig, axis=axis, source_file=p.name, format="xy",
                        x_label=stated, temperature_k=temperature)


XY = PatternFormat(
    name="xy",
    title="Two/three-column ASCII (.xy / .xye)",
    extensions=(".xy", ".xye", ".dat", ".prn", ".txt"),
    sniff="any text file left over that parses as numeric rows. The x column "
          "is 2θ in degrees unless a comment states the x-axis unit: a flight "
          "time (Mantid's 'The X-axis unit is: Time-of-flight') reads it in "
          "microseconds, and any other stated unit is named and refused",
    sigma="the third column when present and positive, else the Poisson fallback",
    # last, but no longer *total*: a file with a NUL in its first 4 kB is not
    # claimed, so a binary vendor pattern reaches identify_format's refusal —
    # which names the formats this build reads — instead of reaching
    # ``read_text`` and dying as a bare UnicodeDecodeError.  "Does this format
    # claim the file" already lives in ``matches``; a separate guard would be a
    # second place that knows about binary files.
    matches=lambda p: not looks_binary(head(p)),
    read=read_xy,
)
