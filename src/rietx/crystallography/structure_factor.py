@dataclass
class PhaseSites:
    """Frozen symmetry-operation subsets for one phase.

    For asymmetric-unit atom ``j``, ``ops[j]`` is a pair of arrays
    ``(R (m_j,3,3), t (m_j,3))`` — the operations that generate *distinct*
    orbit images at the atom's compile-time coordinates.  ``m_j`` is the site
    multiplicity.  ``aniso[j]`` says which Debye-Waller form atom ``j`` uses;
    like the op subsets it is decided at compile time and frozen for the
    stage (it comes from the schema, never from θ).

    ``f_anom[j]`` is the atom's dispersion correction f′ + i·f″, ``None`` when
    the source declares none.  It is frozen for the same reason the op subsets
    are, but more strongly: it depends only on the species and the wavelength,
    and every emission line's wavelength is frozen onto the compiled model
    at stage compile, so f'/f" can never be a function of theta.  (Since
    WP-1134 ``EmissionLine.wavelength`` is a ``Parameter`` and a joint fit may
    free it; that changes when the value is read, not that it is frozen per
    stage, and ``model/forward.py`` carries the argument that still holds --
    the moves are ppm-scale against tables flat on that scale.)

    ``b_coh[j]`` is the atom's **bound coherent neutron scattering length** in
    fm, and its presence is what makes this a neutron phase: set, the amplitude
    is that constant; ``None``, it is the X-ray form factor f₀(species, stol).
    It is frozen on the strongest grounds of the three — a nucleus is a point
    scatterer on this scale, so b has no s dependence *at all*, which is why one
    number per atom suffices where f₀ needs a five-Gaussian expansion evaluated
    per reflection.  Mutually exclusive with ``f_anom``: f′/f″ is an X-ray
    core-level effect, and the two amplitudes are not even in the same units
    (fm against electrons), so a phase carrying both is a modelling error rather
    than a combination to average.
    """

    ops: list[tuple[np.ndarray, np.ndarray]]
    species: list[str]
    aniso: list[bool] = field(default_factory=list)
    f_anom: np.ndarray | None = None  # (n_asym,) complex128
    b_coh: np.ndarray | None = None   # (n_asym,) float64, fm

    def __post_init__(self) -> None:
        if not self.aniso:
            self.aniso = [False] * len(self.species)
        if self.f_anom is not None:
            self.f_anom = np.asarray(self.f_anom, dtype=np.complex128)
            if self.f_anom.shape != (len(self.species),):
                raise ValueError(
                    f"f_anom must have one entry per asymmetric-unit atom "
                    f"({len(self.species)}), got shape {self.f_anom.shape}")
        if self.b_coh is not None:
            self.b_coh = np.asarray(self.b_coh, dtype=np.float64)
            if self.b_coh.shape != (len(self.species),):
                raise ValueError(
                    f"b_coh must have one entry per asymmetric-unit atom "
                    f"({len(self.species)}), got shape {self.b_coh.shape}")
            if self.f_anom is not None:
                raise ValueError(
                    "a phase cannot carry both b_coh (neutron scattering "
                    "lengths, fm) and f_anom (X-ray anomalous dispersion): the "
                    "two amplitudes are different radiations in different units")

    @property
    def n_asym(self) -> int:
        return len(self.species)

    @property
    def any_aniso(self) -> bool:
        return any(self.aniso)


def select_orbit_ops(sg, xyz: np.ndarray, *,
                     tol: float = SITE_TOL) -> tuple[np.ndarray, np.ndarray]:
    """Choose the operation subset giving distinct images of ``xyz``.

    On a general position this is all operations; on a special position, one
    operation per left coset of the site's stabiliser, so each orbit member
    appears exactly once.  :func:`~rietx.crystallography.symmetry.site_orbit`
    is the one authority for that split — the forward model, the Wyckoff
    constraint bases and QPA all read it, and the multiplicity frozen here is
    what ``phase_zmv`` counts atoms with, so a second implementation is a
    second answer to "how many atoms does this site put in the cell".

    The *positions* are not frozen — θ moves the coordinates and the forward
    model recomputes the images from these operations every residual
    evaluation — so no snapped coordinate reaches the fit from here; the split
    is what freezes, per the frozen-per-stage rule.
    """
    orbit = site_orbit(sg, xyz, tol=tol)
    return orbit.rot, orbit.tran


def phase_orbit_split(phase: Phase) -> list[tuple[np.ndarray, np.ndarray]]:
    """Each atom's orbit split, decided from its current coordinates.

    One ``(R, t)`` pair per atom, from :func:`select_orbit_ops`.  The value
    :func:`compile_phase_sites` decides when it is handed none, and what a fit
    decides once at its start and hands to every compile it makes (WP-2052).
    """
    sg = resolve_group(phase.space_group, phase.symmetry_operations)
    return [select_orbit_ops(sg, np.array([a.x.value, a.y.value, a.z.value]))
            for a in phase.atoms]


def _multiplicity_kept_diagnostics(structure, split: list,
                                   ) -> list[Diagnostic]:
    """``SITE_MULTIPLICITY_KEPT`` for each site a fresh compile would recount.

    ``structure`` is a :class:`~rietx.schemas.structure.Structure` at the
    coordinates a fit returns.  A fit decides each site's split once, at its
    start (``Refinement._decide_orbit_split``).  A site whose returned
    coordinates give fewer images at a fresh compile is one the fit carried
    within ``SITE_TOL`` of a special position.  The usual case is a
    half-occupied general atom, a split pair across a mirror, that the data
    do not resolve: its cost is even in the distance off the mirror, so the
    solver stops on it (WP-2052, issue #1088).  The fit counted the site at the
    multiplicity it started with, as GSAS-II does for a whole refinement.
    Every later compile decides from the coordinates, so the message gives the
    atoms per cell both ways and says which one the result used.

    ``split`` is the split the result was measured on.  A compile keeps a
    site's images and never drops them (:func:`compile_phase_sites`), so a
    site reported here has fewer images at a fresh compile than the result
    counted.  The test is arithmetic and has no threshold: any loss is
    reported.
    """
    out: list[Diagnostic] = []
    for i, (phase, ops) in enumerate(zip(structure.phases, split, strict=True)):
        fresh = phase_orbit_split(phase)
        for j, (atom, (rot, _), (rot_now, _)) in enumerate(
                zip(phase.atoms, ops, fresh, strict=True)):
            m_fit, m_now = len(rot), len(rot_now)
            if m_now >= m_fit:
                continue
            occ = atom.occ.value
            on_position = occ * m_fit / m_now
            out.append(Diagnostic(
                level="warning", code="SITE_MULTIPLICITY_KEPT",
                where=[f"phases.{i}.atoms.{j}"],
                value=occ * (m_fit - m_now),
                message=(
                    f"site {atom.label!r} of phase {phase.name!r} was fitted at "
                    f"{m_fit} positions in the cell, the orbit it started the "
                    f"fit with: {m_fit} × {occ:g} = {m_fit * occ:g} atoms per "
                    f"cell. At the coordinates the fit returns, "
                    f"{[round(a.value, 6) for a in (atom.x, atom.y, atom.z)]}, "
                    f"a fresh compile counts {m_now} positions: {m_now} × "
                    f"{occ:g} = {m_now * occ:g} atoms per cell. The result, "
                    f"its statistics and its weight fractions use the fitted "
                    f"count. Later compiles decide from the coordinates and use "
                    f"the fresh count. They include predict() on a new grid, "
                    f"suggest(), a new Refinement and the next fit."),
                suggestion=(
                    f"if the site is one atom on the special position, state "
                    f"it there at occupancy {on_position:g}, which keeps the "
                    f"fitted content; if it is a split pair the data do not "
                    f"resolve, state it more than {TWIN_COORD_TOL:g} "
                    f"(fractional) from the special position, or the next fit "
                    f"counts it at {m_now} positions.")))
    return out


def compile_phase_sites(phase: Phase,
                        f_anom: dict[str, complex] | None = None,
                        *, neutron: bool = False,
                        ops: list[tuple[np.ndarray, np.ndarray]] | None = None,
                        ) -> PhaseSites:
    """Freeze the per-atom symmetry and species data for one stage.

    ``f_anom`` maps a **raw** ``Atom.species`` string (``"Zn2+"``, not the
    normalised form-factor key) to its dispersion correction f′ + i·f″;
    ``None`` leaves the phase non-anomalous.  The caller resolves it, because
    it is a property of the *source* wavelength rather than of the structure —
    see ``model.forward.compile_model``.

    ``neutron=True`` resolves bound coherent scattering lengths instead of X-ray
    form factors, and is decided by the source, not the structure — the same
    division as ``f_anom``.  It refuses to combine with ``f_anom`` for the
    reason given on :class:`PhaseSites`.  Note the *species* normalisation
    differs between the two radiations: an ion resolves to its element for
    f′/f″ because that is a core-level effect, while for b a **mass number is
    kept**, because the isotope is the scatterer (see
    :mod:`rietx.crystallography.neutron`).

    ``ops`` is an orbit split decided earlier, one ``(R, t)`` pair per atom.
    A fit passes the split it decided at its start, so no stage and no
    closing compile takes images away from a site that has moved onto a
    special position (WP-2052).  A site whose current coordinates need *more*
    images than ``ops`` holds has left a special position, which a rigid
    body's pose can do, and gets the current split: fewer images than its
    position has is no structure at all.  ``None`` decides every site here.
    """
    fresh = phase_orbit_split(phase)
    if ops is None:
        ops = fresh
    elif len(ops) != len(phase.atoms):
        raise ValueError(
            f"phase {phase.name!r}: an orbit split for {len(ops)} atoms was "
            f"handed to a phase of {len(phase.atoms)}")
    ops = [kept if len(kept[0]) >= len(now[0]) else now
           for kept, now in zip(ops, fresh, strict=True)]
    species: list[str] = []
    aniso: list[bool] = []
    for atom in phase.atoms:
        # The species convention follows the RADIATION.  The X-ray normaliser
        # validates against Waasmaier-Kirfel coefficients, which no isotope
        # has and a neutron phase never needs: it resolves ``b_coh`` below and
        # reaches ``f0`` nowhere.  Running it unconditionally discarded the
        # isotope convention one line above the lookup that implements it, so
        # D, 2H and 7Li raised "no Waasmaier-Kirfel coefficients" — the
        # headline neutron case, on a table that has had b(2H) all along.
        species.append(neutron_normalize_species(atom.species) if neutron
                       else normalize_species(atom.species))
        aniso.append(atom.aniso is not None)
    fa = None
    if f_anom is not None:
        fa = np.array([complex(f_anom[a.species]) for a in phase.atoms],
                      dtype=np.complex128)
    b = None
    if neutron:
        if f_anom is not None:
            raise ValueError(
                f"phase {phase.name!r}: neutron scattering lengths and X-ray "
                f"anomalous dispersion cannot both apply")
        b = np.array([neutron_b_coh(a.species) for a in phase.atoms],
                     dtype=np.float64)
    return PhaseSites(ops=ops, species=species, aniso=aniso, f_anom=fa,
                      b_coh=b)


def transposed_rotation_indices(hkl: np.ndarray, rot: np.ndarray) -> np.ndarray:
    """q_mn = R_mᵀ·h_n for every op and reflection, shape (m, N, 3).

    The reciprocal-space action is the **transposed** rotation (see the
    comment in ``symmetry.py``); getting this wrong is invisible in cubic
    settings and wrong everywhere else.
    """
    xp = get_backend()
    return xp.einsum("nk,mkc->mnc", xp.asarray(hkl, dtype=np.float64), rot)


def _aniso_dw(hkl: np.ndarray, rot: np.ndarray, u6, astar: np.ndarray) -> np.ndarray:
    """exp(−2π² qᵀU*q) per (op, reflection), shape (m, N)."""
    xp = get_backend()
    q = transposed_rotation_indices(hkl, rot)
    ustar = ustar_from_ucif(u6, astar)
    return xp.exp(-2.0 * xp.pi ** 2 * xp.einsum("mnc,cd,mnd->mn", q, ustar, q))


def _orbit_terms(hkl, stol, sites, xyz, occ, biso, uaniso, astar, j):
    """Per-atom pieces of F: ``(amp_a, amp_b, phase (m,N), dw (m,N) | None)``.

    ``amp_a`` is the real prefactor occ·(f₀ + f′) that multiplies the orbit sum
    in A and ``amp_b`` the occ·f″ one that multiplies it in B — both **(N,)**,
    which the derivative kernels rely on (see the module docstring).  ``amp_b`` is ``None`` — not a zero array — when the
    phase carries no dispersion, so the off path does no arithmetic at all;
    that test is compile-time structural (``sites.f_anom``), never a branch on
    θ, so it does not break residual purity.  ``dw`` is the per-image
    Debye-Waller factor, ``None`` for isotropic sites (whose factor is already
    folded into the amplitudes).  Sharing this between the forward model and
    the two derivative routines is what keeps their expansions of F literally
    the same expression.

    The amplitude is deliberately built as ``occ·f·dw`` in that association
    order: fp multiplication is not associative, and regrouping it (say to
    share an ``occ·dw`` prefactor between A and B) moves the non-anomalous
    path off its backend goldens by an ulp.
    """
    xp = get_backend()
    rot, tran = sites.ops[j]
    # xp.matmul / xp.asarray, not bare `rot @ … + tran`: the frozen numpy
    # constants must not meet a traced value through a python operator at all
    # (see backend/api.py's module docstring)
    positions = xp.matmul(rot, xyz[j]) + xp.asarray(tran, dtype=np.float64)  # (m, 3)
    phase = xp.exp(2.0j * xp.pi * (positions @ hkl.T))  # (m, N)
    fa = None if sites.f_anom is None else sites.f_anom[j]
    if sites.b_coh is None:
        f = f0(sites.species[j], stol)
        if fa is not None:
            f = f + float(fa.real)
    else:
        # A nucleus is a point scatterer on this scale, so b has no s
        # dependence.  Broadcast to (N,) anyway rather than passing a scalar:
        # the anisotropic branch below builds ``amp_b`` with ``full_like(f, …)``
        # and the derivative kernels index amplitudes as ``amp[:, None]``, so
        # every amplitude in this module is reflection-shaped by contract.
        # ``full_like(stol, …)`` also keeps the constant off the left of a
        # python operator against a θ-derived value (see backend/api.py).
        f = xp.full_like(stol, float(sites.b_coh[j]))
    if sites.aniso[j]:
        dw = _aniso_dw(hkl, rot, uaniso[j], astar)
        # broadcast to (N,) like every other amplitude: f″ is reflection-
        # independent, but an anisotropic site's ``f`` carries no per-reflection
        # Debye-Waller factor to spread it, and the derivative kernels index
        # both amplitudes as ``amp[:, None]``
        amp_b = None if fa is None else xp.full_like(f, occ[j] * float(fa.imag))
        return occ[j] * f, amp_b, phase, dw
    dw = xp.exp(-biso[j] * stol * stol)  # exp(−B (sinθ/λ)²)
    amp_b = None if fa is None else occ[j] * float(fa.imag) * dw
    return occ[j] * f * dw, amp_b, phase, None


def _orbit_sum(phase: np.ndarray, dw: np.ndarray | None) -> np.ndarray:
    """Σ_m T_m·exp(2πi h·x_m) — the isotropic T factored out already."""
    return phase.sum(axis=0) if dw is None else (phase * dw).sum(axis=0)


def _structure_factors_ab(h, stol, sites, xyz, occ, biso, uaniso, astar):
    """(A, B) of the module docstring; ``B`` is ``None`` without dispersion."""
    xp = get_backend()
    A = xp.zeros(len(h), dtype=np.complex128)
    B = None if sites.f_anom is None else xp.zeros(len(h), dtype=np.complex128)
    for j in range(sites.n_asym):
        amp_a, amp_b, phase, dw = _orbit_terms(
            h, stol, sites, xyz, occ, biso, uaniso, astar, j)
        orbit = _orbit_sum(phase, dw)
        A = A + amp_a * orbit
        if B is not None:
            B = B + amp_b * orbit
    return A, B


def _abs2(z) -> np.ndarray:
    xp = get_backend()
    return xp.real(z * xp.conj(z))


def structure_factors_squared(
    hkl: np.ndarray,
    d: np.ndarray,
    sites: PhaseSites,
    xyz: np.ndarray,
    occ: np.ndarray,
    biso: np.ndarray,
    uaniso: np.ndarray | None = None,
    astar: np.ndarray | None = None,
) -> np.ndarray:
    """Powder |F(hkl)|² for each reflection — Friedel-averaged (see module docs).

    Without dispersion this is |F|² exactly as before; with it, the value
    returned is ⟨|F|²⟩ = |A|² + |B|², the average over the ±h orbit the powder
    peak actually contains.

    Parameters
    ----------
    hkl, d : (N,3) reflection indices and current d-spacings (Å).
    sites : frozen per-atom symmetry-operation subsets (and f′ + i·f″).
    xyz : (n_asym, 3) current fractional coordinates.
    occ, biso : (n_asym,) occupancies and isotropic B (Å²).
    uaniso : (n_asym, 6) CIF U^ij (Å²) in (11, 22, 33, 12, 13, 23) order.
        Only rows where ``sites.aniso[j]`` is set are read; required when any
        are.  ``astar`` is then the (3,) reciprocal axis lengths of the
        current cell (they move with the cell, hence a per-call argument
        rather than something frozen into ``sites``).
    """
    xp = get_backend()
    stol = 1.0 / (2.0 * xp.asarray(d, dtype=np.float64))  # s = sinθ/λ = 1/(2d)
    h = xp.asarray(hkl, dtype=np.float64)
    A, B = _structure_factors_ab(h, stol, sites, xyz, occ, biso, uaniso, astar)
    return _abs2(A) if B is None else _abs2(A) + _abs2(B)


def d_f2_d_xyz(
    hkl: np.ndarray,
    d: np.ndarray,
    sites: PhaseSites,
    xyz: np.ndarray,
    occ: np.ndarray,
    biso: np.ndarray,
    j: int,
    uaniso: np.ndarray | None = None,
    astar: np.ndarray | None = None,
) -> np.ndarray:
    """Analytic ∂⟨|F|²⟩/∂x_j over the frozen op subsets, shape (N, 3).

    With A = Σ_j' a_j'·G_j', a_j the real occ·(f₀+f′)(·Debye-Waller, isotropic
    sites only) prefactor and G_j = Σ_m T_jm·exp(2πi h·(R_m x_j + t_m)),

        ∂A/∂x_jc = a_j · 2πi Σ_m (R_mᵀ h)_c · T_jm · exp(2πi h·(R_m x_j + t_m))

    — the reciprocal-space action is the **transposed** rotation (see
    ``symmetry.py``) — and ∂|A|²/∂x_jc = 2·Re(Ā · ∂A/∂x_jc) (structure-
    factor derivatives per Rietveld, 1969, J. Appl. Cryst. 2, 65).  T_jm is
    the per-image Debye-Waller factor, which is constant over the orbit for
    an isotropic site and image-dependent for an anisotropic one; either way
    it is independent of x_j, so it rides along unchanged.  The op subsets
    are the same frozen ``sites.ops`` the forward model uses, so the gradient
    is exact for the model as compiled.

    B differs from A only in its per-atom prefactor, so it shares the whole
    bracketed sum: the anomalous term costs one extra multiply-and-accumulate,
    not a second expansion.
    """
    xp = get_backend()
    stol = 1.0 / (2.0 * xp.asarray(d, dtype=np.float64))  # s = sinθ/λ = 1/(2d)
    h = xp.asarray(hkl, dtype=np.float64)
    A = xp.zeros(len(h), dtype=np.complex128)
    B = None if sites.f_anom is None else xp.zeros(len(h), dtype=np.complex128)
    dA = xp.zeros((len(h), 3), dtype=np.complex128)
    dB = None if B is None else xp.zeros((len(h), 3), dtype=np.complex128)
    for jj in range(sites.n_asym):
        amp_a, amp_b, phase, dw = _orbit_terms(
            h, stol, sites, xyz, occ, biso, uaniso, astar, jj)
        orbit = _orbit_sum(phase, dw)
        A = A + amp_a * orbit
        if B is not None:
            B = B + amp_b * orbit
        if jj == j:
            rth = transposed_rotation_indices(h, sites.ops[jj][0])  # (m, N, 3)
            weighted = phase if dw is None else phase * dw
            bracket = (weighted[:, :, None] * rth).sum(axis=0)
            dA = amp_a[:, None] * (2.0j * xp.pi) * bracket
            if dB is not None:
                dB = amp_b[:, None] * (2.0j * xp.pi) * bracket
    out = 2.0 * xp.real(xp.conj(A)[:, None] * dA)
    if B is not None:
        out = out + 2.0 * xp.real(xp.conj(B)[:, None] * dB)
    return out


def d_f2_d_uaniso(
    hkl: np.ndarray,
    d: np.ndarray,
    sites: PhaseSites,
    xyz: np.ndarray,
    occ: np.ndarray,
    biso: np.ndarray,
    j: int,
    uaniso: np.ndarray,
    astar: np.ndarray,
) -> np.ndarray:
    """Analytic ∂⟨|F|²⟩/∂U^ij for anisotropic atom ``j``, shape (N, 6).

    The exponent of the image-m Debye-Waller factor is

        E_m = −2π² Σ_cd q_c q_d a*_c a*_d U^cd,      q = R_mᵀ h,

    so with the six components stored as (11, 22, 33, 12, 13, 23) the packed
    partials pick up the usual factor of two off the diagonal (U^cd and U^dc
    are the same stored number):

        ∂E_m/∂U^cd = −2π² a*_c a*_d q_c q_d · (1 if c = d else 2)

    and ∂A/∂U^cd = a_j·Σ_m T_jm·exp(2πi h·x_jm)·∂E_m/∂U^cd, closed by
    ∂|A|²/∂U = 2·Re(Ā·∂A/∂U) and the matching B term (see
    :func:`d_f2_d_xyz` — the per-component sum is shared, only the prefactor
    differs).  Columns are in the same order as
    ``crystallography.adp.U_NAMES``, which is what the Wyckoff ADP constraint
    rows are written in.

    Like :func:`d_f2_d_xyz` this is Jacobian *support* — host-side analytic
    columns, never traced by an autodiff backend (which differentiates the
    residual itself) — so the in-place per-component buffer writes are fine.
    """
    xp = get_backend()
    stol = 1.0 / (2.0 * xp.asarray(d, dtype=np.float64))  # s = sinθ/λ = 1/(2d)
    h = xp.asarray(hkl, dtype=np.float64)
    s = xp.asarray(astar, dtype=np.float64)
    A = xp.zeros(len(h), dtype=np.complex128)
    B = None if sites.f_anom is None else xp.zeros(len(h), dtype=np.complex128)
    dA = np.zeros((len(h), 6), dtype=np.complex128)
    dB = None if B is None else np.zeros((len(h), 6), dtype=np.complex128)
    for jj in range(sites.n_asym):
        amp_a, amp_b, phase, dw = _orbit_terms(
            h, stol, sites, xyz, occ, biso, uaniso, astar, jj)
        orbit = _orbit_sum(phase, dw)
        A = A + amp_a * orbit
        if B is not None:
            B = B + amp_b * orbit
        if jj == j:
            if dw is None:
                raise ValueError(f"atom {j} is isotropic: no U^ij to differentiate")
            q = transposed_rotation_indices(h, sites.ops[jj][0])  # (m, N, 3)
            for v, (c, e) in enumerate(VOIGT):
                fold = 1.0 if c == e else 2.0
                de = (-2.0 * xp.pi ** 2 * fold * s[c] * s[e]) * q[:, :, c] * q[:, :, e]
                bracket = (phase * dw * de).sum(axis=0)
                dA[:, v] = amp_a * bracket
                if dB is not None:
                    dB[:, v] = amp_b * bracket
    out = 2.0 * xp.real(xp.conj(A)[:, None] * dA)
    if B is not None:
        out = out + 2.0 * xp.real(xp.conj(B)[:, None] * dB)
    return out
