#: How many directions a point group's origin floats in: the ten polar point
#: groups, from their symbols (ITA Part 10's polar classes), and nothing for the
#: other 22.  A table independent of the rotation algebra under test.
_FLOATING_DIMENSION = {"1": 3, "m": 2, "2": 1, "mm2": 1, "3": 1, "3m": 1,
                       "4": 1, "4mm": 1, "6": 1, "6mm": 1}


def _intensities_after_shift(sg, seed_xyz, shift, hkl):
    """|F|² of one general site's orbit after moving the site by ``shift``.

    The site is moved and its images regenerated by the group's operations,
    so the images move by R·shift, not by shift.  The intensities are then
    unchanged for every reflection exactly when R·shift = shift for every R:
    the physical statement of a floating origin, with no rotation algebra of
    the package in it.
    """
    xyz = np.asarray(seed_xyz, dtype=float) + np.asarray(shift, dtype=float)
    images = np.array([np.asarray(op.apply_to_xyz(list(xyz)), dtype=float)
                       for op in sg.operations()])
    phase = 2j * np.pi * (hkl @ images.T)
    return np.abs(np.exp(phase).sum(axis=1)) ** 2


def test_every_gemmi_setting_floats_along_exactly_the_shifts_no_intensity_sees():
    """Which directions, never how many (root CLAUDE.md, the cell-ties rule).

    For all 564 of gemmi's settings: the basis has the dimension the point
    group's symbol implies, each row is a shift that leaves every intensity
    unchanged when the site is moved and re-expanded, and the rows are
    independent.  Those three together make the span the floating subspace
    itself.  A shift outside the span is checked to change an intensity, so the
    oracle can fail.
    """
    import gemmi

    rng = np.random.default_rng(1912)
    hkl = rng.integers(-4, 5, size=(40, 3)).astype(float)
    seed = [0.1234, 0.3417, 0.0712]
    checked = 0
    for sg in gemmi.spacegroup_table():
        basis = floating_origin_basis(sg)
        assert len(basis) == _FLOATING_DIMENSION.get(sg.point_group_hm(), 0), sg.xhm()
        if len(basis):
            assert np.linalg.matrix_rank(basis) == len(basis), sg.xhm()
        base = _intensities_after_shift(sg, seed, [0, 0, 0], hkl)
        for row in basis:
            moved = _intensities_after_shift(sg, seed, 0.037 * row, hkl)
            assert np.allclose(moved, base, rtol=1e-9, atol=1e-6), (sg.xhm(), row)
        if len(basis) < 3:
            outside = rng.normal(size=3)
            if len(basis):
                q, _ = np.linalg.qr(basis.T.astype(float))
                outside -= q @ (q.T @ outside)
            moved = _intensities_after_shift(sg, seed, 0.037 * outside, hkl)
            assert not np.allclose(moved, base, rtol=1e-6, atol=1e-3), sg.xhm()
        checked += 1
    assert checked == 564


def _zno(z_zn: float = 0.0, z_o: float = 0.382):
    P = rx.Parameter

    def atom(label, species, x, y, z, b):
        return rx.Atom(label=label, species=species, x=P(value=x), y=P(value=y),
                       z=P(value=z), biso=P(value=b))

    return rx.Phase(
        name="zno", space_group="P 63 m c",
        cell=rx.Cell(a=P(value=3.2495), b=P(value=3.2495), c=P(value=5.2069),
                     alpha=P(value=90.0), beta=P(value=90.0),
                     gamma=P(value=120.0)),
        scale=P(value=0.01),
        atoms=[atom("Zn", "Zn", 1 / 3, 2 / 3, z_zn, 0.5),
               atom("O", "O", 1 / 3, 2 / 3, z_o, 0.6)])


def _pattern():
    grid = np.arange(15.0, 100.0, 0.02)
    truth = rx.Refinement(rx.Structure(phases=[_zno()]),
                          rx.Instrument.bragg_brentano(radiation="CuKa"),
                          history=False)
    y = np.asarray(truth.predict(grid)) + 50.0
    y = np.maximum(y + np.random.default_rng(3).normal(
        scale=np.sqrt(np.maximum(y, 1.0))), 0)
    return rx.PatternData(two_theta=grid.tolist(), intensity=y.tolist())


PLAN = rx.RefinementPlan(stages=[
    rx.Stage("scale", ["phases.*.scale", "instrument.background.c*"]),
    rx.Stage("xyz", ["phases.*.scale", "instrument.background.c*",
                     "phases.*.atoms.*.dof.*"])])


def test_a_hold_leaves_one_z_and_the_other_is_quoted_against_it():
    data = _pattern()
    ins = rx.Instrument.bragg_brentano(radiation="CuKa")
    ins.background = rx.auto_background(data).background
    # a start displaced along c: the pair's common shift changes no intensity
    free = rx.Refinement(rx.Structure(phases=[_zno(0.05, 0.432)]), ins,
                         history=False)
    held = rx.Refinement(rx.Structure(phases=[_zno(0.05, 0.432)]), ins,
                         history=False)
    diagnostics = held.hold_floating_origin()
    assert [d.code for d in diagnostics] == ["ORIGIN_FIXED_ON_POLAR_AXIS"]
    assert diagnostics[0].where == ["phases.0.atoms.0.dof.0"]

    r_free = free.fit(data, plan=PLAN, telemetry=False)
    r_held = held.fit(data, plan=PLAN, telemetry=False)
    z = lambda ref, i: ref.fitted_structure.phases[0].atoms[i].z.value  # noqa: E731
    # held: Zn stays at its start, and O moves to the right distance from it
    assert z(held, 0) == pytest.approx(0.05, abs=1e-12)
    assert z(held, 1) - z(held, 0) == pytest.approx(0.382, abs=5e-3)
    # not held: the pair is free to slide and the fit says so
    assert "FLAT_DIRECTION" in {d.code for d in r_free.diagnostics}
    assert "FLAT_DIRECTION" not in {d.code for d in r_held.diagnostics}
    # the same fit quality, so nothing was lost by holding
    assert r_held.statistics.rwp == pytest.approx(r_free.statistics.rwp, rel=1e-2)
    # the default does nothing: a refinement never asked holds nothing
    assert not rx.Refinement(rx.Structure(phases=[_zno()]), ins,
                             history=False)._user_holds


def test_a_non_polar_group_holds_nothing():
    P = rx.Parameter
    ins = rx.Instrument.bragg_brentano(radiation="CuKa")
    polar = rx.Refinement(rx.Structure(phases=[_zno()]), ins, history=False)
    assert len(polar.hold_floating_origin()) == 1
    pnma = rx.Phase(
        name="p", space_group="P n m a",
        cell=rx.Cell(a=P(value=5.7), b=P(value=7.7), c=P(value=5.5),
                     alpha=P(value=90.0), beta=P(value=90.0), gamma=P(value=90.0)),
        atoms=[rx.Atom(label="La", species="La", x=P(value=0.05), y=P(value=0.25),
                       z=P(value=0.99), biso=P(value=0.5))])
    ref = rx.Refinement(rx.Structure(phases=[pnma]), ins, history=False)
    assert ref.hold_floating_origin() == [] and not ref._user_holds


# ------------------------------------------------- the hold in the table (WP-1912)
def _declared(phase):
    phase.floating_origin = "hold"
    return phase


def _cell(a, b, c, gamma=90.0):
    P = rx.Parameter
    return rx.Cell(a=P(value=a), b=P(value=b), c=P(value=c), alpha=P(value=90.0),
                   beta=P(value=90.0), gamma=P(value=gamma))


def _atom(label, species, x, y, z):
    P = rx.Parameter
    return rx.Atom(label=label, species=species, x=P(value=x), y=P(value=y),
                   z=P(value=z), biso=P(value=0.5))


def _table(*phases):
    return ParameterTable(rx.Structure(phases=list(phases)),
                          rx.Instrument.bragg_brentano(radiation="CuKa"))


def test_the_table_holds_the_first_atom_along_the_axis_and_a_glob_skips_it():
    table = _table(_declared(_zno()))
    assert table.origin_holds == {"phases.0.atoms.0.dof.0": (0, (0, 0, 1))}
    assert table.set_vary(["phases.*.atoms.*.dof.*"], True) == [
        "phases.0.atoms.1.dof.0"]


def test_undeclared_the_table_is_the_one_it_always_was():
    off, on = _table(_zno()), _table(_declared(_zno()))
    assert not off.origin_holds and not off.origin_phases
    assert not any(e.held for e in off.entries)
    # the declaration changes one row, and only by holding it
    changed = [a.path for a, b in zip(off.entries, on.entries, strict=True)
               if a != b]
    assert changed == ["phases.0.atoms.0.dof.0"]


