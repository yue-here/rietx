"""A seeded planted-events series: which events the series result carries (#141).

``tests/planted_series.py`` forward-models a cooling ramp of a cubic perovskite
with four events planted at known indices (a background step, a blank frame,
an unmodelled second phase growing, a cubic → tetragonal transition) and a
null twin with none.  The chain is fitted with one fixed cubic model, and each
event is looked for in the result's own vocabulary
(:func:`tests.planted_series.surfaced`, read off ``SeriesResult`` alone —
WP-1317's rule that the flag list and the event markers are one vocabulary).

These tests check **recovery of planted events**, not accuracy on real data: the
patterns are generated by the same forward model the fit then uses, so a pass says
the series result can see an event the model can express, and nothing about a
measured series.  WP-1317 is the work this serves; WP-1965 is its second user.

The point is calibration (WP-1325, WP-1965): a fitting or detector change that
moves where, or whether, a planted event surfaces fails here.  An event the
result does not carry yet is a **strict** xfail, so the test goes red the day
something makes it visible and the marker can come off.

Measured at 24 patterns over seeds 0-7 and at 248 over seeds 0-4: every
event's outcome below holds on every seed, and seed 0 is the one pinned.
Since WP-2003 a step is read by rank, the largest its path took
(:func:`tests.planted_series.largest_steps`), never against a threshold;
re-measured then at 24 patterns on seeds 0-7 and at 248 on seed 0.  The null
is clean at 24 patterns on all eight seeds; at 248 on seeds 0, 2, 3 and 4
(the strict xfail at the end says why not 1).  Since WP-2003's C1 a high Rwp
is ``SeriesEntry.rwp_over_median``, a record with no threshold, and the run
above the 1.25 fence that marked the second phase and the transition planted
alone is gone with ``SEQUENTIAL_RWP_OUTLIER``: re-measured on seed 0 at 24
and 248, both are now strict xfails.
"""

import json
