"""A seeded planted-events series: which events the series result carries (#141).

``tests/planted_series.py`` forward-models a cooling ramp of a cubic perovskite
with four events planted at known indices (a background step, a blank frame,
an unmodelled second phase growing, a cubic → tetragonal transition) and a
null twin with none.  The chain is fitted with one fixed cubic model, and each
event is looked for in the result's own vocabulary
(:func:`tests.planted_series.surfaced`, read off ``SeriesResult`` alone —
WP-1317's rule that the flag list and the event markers are one vocabulary).

These tests check **recovery of planted events**, not accuracy on real data: the
patterns are generated by the same forward model the fit then uses, so a pass says
the series result can see an event the model can express, and nothing about a
measured series.  WP-1317 is the work this serves; WP-1965 is its second user.

The point is calibration (WP-1325, WP-1965): a fitting or detector change that
moves where, or whether, a planted event surfaces fails here.  An event the
result does not carry yet is a **strict** xfail, so the test goes red the day
something makes it visible and the marker can come off.

Measured at 24 patterns over seeds 0-7 and at 248 over seeds 0-4: every
event's outcome below holds on every seed, and seed 0 is the one pinned.  The
null is clean at 24 patterns on all eight seeds; at 248 it is clean on seed 0
only (the strict xfail at the end says why).
"""

import json
from pathlib import Path

import pytest

from rietx.model import compiled
from tests.planted_series import (
    EVENTS,
    default_events,
    generate,
    null_series,
    numpy_path,
    refine,
    second_phase_tolerance,
    signals,
    surfaced,
)

pytestmark = pytest.mark.xdist_group("planted-series")

#: long enough for every event to sit five patterns from the next, and for
#: the discontinuity scan's five-point minimum on each side; ~6 s for the
#: three fits on an arm64 Mac
LENGTH = 24
SEED = 0
EVENT_AT = default_events(LENGTH)
#: the committed full-length output (``python -m tests.planted_series``)
DATA = Path(__file__).parent / "data" / "planted_series"
#: series-level codes that mark an event; ``SEQUENTIAL_PERSISTENT_FINDING``
#: describes the model rather than a point of the series and is not one
EVENT_CODES = {"SEQUENTIAL_RWP_OUTLIER", "SEQUENTIAL_RESEED",
               "SEQUENTIAL_UNRECOVERED", "SEQUENTIAL_DISCONTINUITY",
               "SEQUENTIAL_WIDTH_GROWTH"}

_MASKED = ("the transition falls inside the second phase's run of patterns "
           "above the Rwp fence, and nothing in the result marks it: no run "
           "starts there, and the discontinuity scan skips every step into or "
           "out of a pattern above the fence, so the cubic cell's jump is not "
           "scanned.  Only the RWP_OUTLIER ratio (a value, not a code) doubles "
           "there.  Planted alone, the transition is carried "
           "(test_the_transition_alone_starts_a_run_above_the_fence)")


@pytest.fixture(scope="module")
def planted():
    return refine(generate(LENGTH, seed=SEED))


@pytest.fixture(scope="module")
def null():
    return refine(null_series(LENGTH, seed=SEED))


@pytest.fixture(scope="module")
def transition_alone():
    at = EVENT_AT["transition"]
    return refine(generate(LENGTH, seed=SEED, events={"transition": at}))


def test_the_generator_and_the_refit_declare_the_numpy_path():
    """Every pinned outcome here, and the committed 248-pattern output the slow
    row compares byte for byte, is produced with the kernel tier off
    (``tests/CLAUDE.md`` § Quoting numbers), whatever the machine would pick,
    and the caller's setting is restored."""
    assert hasattr(generate, "__wrapped__") and hasattr(refine, "__wrapped__")
    seen = []
    probe = numpy_path(lambda: seen.append(compiled.enabled()))
    was = compiled.set_enabled(True)
    try:
        probe()
        assert seen == [False]
        assert compiled.set_enabled(True) is True
    finally:
        compiled.set_enabled(was)


def test_the_null_series_raises_no_event_signal(null):
    sig = signals(null)
    assert sig["above_fence"] == sig["steps"] == sig["reseeded"] == []
    assert sig["unrecovered"] == sig["phase_unconstrained"] == []
    assert not {code for code, _ in sig["codes"]} & EVENT_CODES
    assert {k: surfaced(null, k, i) for k, i in EVENT_AT.items()} == dict.fromkeys(
        EVENTS)


def test_the_background_step_is_a_flagged_step_on_its_constant(planted):
    at = EVENT_AT["background"]
    assert surfaced(planted, "background", at) == (
        f"SEQUENTIAL_DISCONTINUITY instrument.background.c0 ({at - 1}, {at})")


def test_the_blank_frame_is_a_step_in_the_scale_and_an_unconstrained_phase(planted):
    """Not an Rwp outlier: with the Bragg signal gone a background-dominated
    frame's Rwp is 1.1-1.2× its neighbours', under the 1.25 fence.  What marks
    it is the scale stepping to zero and back, and the frame's own
    ``PHASE_UNCONSTRAINED``."""
    at = EVENT_AT["bad"]
    found = surfaced(planted, "bad", at)
    assert found is not None
    assert found.startswith("SEQUENTIAL_DISCONTINUITY phases.0.scale")
    assert signals(planted)["phase_unconstrained"] == [at]


def test_the_second_phase_starts_a_run_above_the_fence(planted):
    at = EVENT_AT["second_phase"]
    found = surfaced(planted, "second_phase", at)
    assert found is not None, signals(planted)["above_fence"]
    # …and the run lasts to the end: the median the fence follows excludes it
    above = signals(planted)["above_fence"]
    assert above == list(range(above[0], LENGTH))
    assert at <= above[0] <= at + second_phase_tolerance(LENGTH, at)


@pytest.mark.xfail(strict=True, reason=_MASKED)
def test_the_transition_is_marked_in_the_planted_series(planted):
    at = EVENT_AT["transition"]
    assert surfaced(planted, "transition", at) is not None


def test_the_transition_alone_starts_a_run_above_the_fence(transition_alone):
    at = EVENT_AT["transition"]
    assert surfaced(transition_alone, "transition", at) == (
        f"SEQUENTIAL_RWP_OUTLIER run from {at}")
    assert signals(transition_alone)["above_fence"] == list(range(at, LENGTH))


def test_each_matcher_is_specific_to_its_own_event(planted):
    """No event's rule is satisfied by another event at another index: each
    rule, moved to every index where nothing was planted, finds nothing."""
    planted_at = set(EVENT_AT.values())
    for kind in ("background", "bad"):
        hits = [i for i in range(1, LENGTH) if i not in planted_at
                and abs(i - EVENT_AT[kind]) > 1
                and surfaced(planted, kind, i) is not None]
        assert hits == [], kind


def test_the_committed_output_carries_the_same_mapping():
    """The committed 248-pattern ``signals.json`` says what this module's
    rules say about it, so the file and the rules cannot drift apart."""
    record = json.loads((DATA / "signals.json").read_text(encoding="utf-8"))
    assert record["length"] == 248
    assert set(record["events"]) == set(EVENTS)
    assert record["surfaced"]["transition"] is None
    assert all(record["surfaced"][k] for k in ("background", "bad", "second_phase"))
    null_record = json.loads((DATA / "null_signals.json").read_text(encoding="utf-8"))
    assert null_record["events"] == {}
    assert null_record["signals"]["above_fence"] == null_record["signals"]["steps"] == []


@pytest.mark.slow
def test_the_full_length_series_reproduces_its_committed_signals():
    """The 248-pattern series of #141, regenerated and refitted (35-60 s for both
    arms), on the numpy path the fixtures declare: every signal except the reseeds — which follow the ladder's first
    rung budget and mark no event — equals the committed record, and the
    null's is empty."""
    series = generate(248, seed=0)
    record = json.loads((DATA / "signals.json").read_text(encoding="utf-8"))
    result = refine(series)
    got = signals(result)
    for key in ("above_fence", "steps", "unrecovered", "phase_unconstrained"):
        assert got[key] == record["signals"][key], key
    assert {k: surfaced(result, k, i) for k, i in series.events.items()} == (
        record["surfaced"])

    null_result = refine(null_series(248, seed=0))
    assert signals(null_result) == json.loads(
        (DATA / "null_signals.json").read_text(encoding="utf-8"))["signals"]


_LOOK_ELSEWHERE = (
    "SEQUENTIAL_DISCONTINUITY's bar (5x the path's median step and 3 combined "
    "esds) is per step, so on a clean chain its false flags grow with the "
    "number of steps times paths: at 248 patterns the null raised 1, 1, 4 and "
    "3 flagged steps on seeds 1-4 (scale, U, V, W, zero shift, background "
    "constant; 5-7x the median, every fit warm with GoF near 1), and none on "
    "seed 0, the one committed; at 24 patterns, none on seeds 0-7")


@pytest.mark.slow
@pytest.mark.xfail(strict=True, reason=_LOOK_ELSEWHERE)
def test_a_full_length_null_raises_no_step_on_any_seed():
    """60-100 s: five 248-pattern null chains."""
    flagged = {seed: signals(refine(null_series(248, seed=seed)))["steps"]
               for seed in range(5)}
    assert flagged == dict.fromkeys(range(5), [])
