def test_each_matcher_is_specific_to_its_own_event(planted):
    """No event's rule is satisfied by another event at another index: each
    rule, moved to every index where nothing was planted, finds nothing."""
    planted_at = set(EVENT_AT.values())
    for kind in ("background", "bad"):
        hits = [i for i in range(1, LENGTH) if i not in planted_at
                and abs(i - EVENT_AT[kind]) > 1
                and surfaced(planted, kind, i) is not None]
        assert hits == [], kind


def test_the_committed_output_carries_the_same_mapping():
    """The committed 248-pattern ``signals.json`` says what this module's
    rules say about it, so the file and the rules cannot drift apart."""
    record = json.loads((DATA / "signals.json").read_text(encoding="utf-8"))
    assert record["length"] == 248
    assert set(record["events"]) == set(EVENTS)
    assert record["surfaced"]["transition"] is None
    assert record["surfaced"]["second_phase"] is None      # WP-2003, C1
    assert all(record["surfaced"][k] for k in ("background", "bad"))
    null_record = json.loads((DATA / "null_signals.json").read_text(encoding="utf-8"))
    assert null_record["events"] == {}
    assert null_record["signals"]["reseeded"] == []


@pytest.mark.slow
def test_the_full_length_series_reproduces_its_committed_signals():
    """The 248-pattern series of #141, regenerated and refitted (35-60 s for both
    arms), on the numpy path the fixtures declare: every signal except the reseeds — which follow the ladder's first
    rung budget and mark no event — equals the committed record, and the
    null's is empty."""
    series = generate(248, seed=0)
    record = json.loads((DATA / "signals.json").read_text(encoding="utf-8"))
    result = refine(series)
    got = signals(result)
    for key in ("steps", "unrecovered", "phase_unconstrained"):
        assert got[key] == record["signals"][key], key
    _same_ratios(got, record["signals"])
    assert {k: surfaced(result, k, i) for k, i in series.events.items()} == (
        record["surfaced"])

    null_result = refine(null_series(248, seed=0))
    null_got = signals(null_result)
    null_record = json.loads(
        (DATA / "null_signals.json").read_text(encoding="utf-8"))["signals"]
    _same_ratios(null_got, null_record)
    assert ({k: v for k, v in null_got.items() if k != "rwp_over_median"}
            == {k: v for k, v in null_record.items() if k != "rwp_over_median"})


def _same_ratios(got: dict, committed: dict) -> None:
    """The ratios at three figures, to one unit in the last: a converged fit's
    Rwp moves in its last digits across platforms' libm, while every index is
    exact."""
    assert [i for i, _ in got["rwp_over_median"]] == [
        i for i, _ in committed["rwp_over_median"]]
    for (i, r), (_, c) in zip(got["rwp_over_median"], committed["rwp_over_median"],
                              strict=True):
        assert r == pytest.approx(c, rel=1e-2), i


_LOOK_ELSEWHERE = (
    "a largest step is a rank, one per path, so on a clean chain it lands "
    "somewhere and can land on an event's index by chance: at 248 patterns "
    "the null's scale stepped most at 87->88 on seed 1, the blank frame's "
    "index (WP-2003, measured on Linux; seeds 0, 2, 3 and 4 surface nothing, "
    "and at 24 patterns none of seeds 0-7 does).  Under the threshold it "
    "replaced, false flags grew with steps times paths instead (1, 1, 4 and 3 "
    "on seeds 1-4)")


@pytest.mark.slow
@pytest.mark.xfail(strict=True, reason=_LOOK_ELSEWHERE)
def test_a_full_length_null_surfaces_no_event_on_any_seed():
    """60-100 s: five 248-pattern null chains."""
    at = default_events(248)
    for seed in range(5):
        result = refine(null_series(248, seed=seed))
        assert {k: surfaced(result, k, i) for k, i in at.items()} == dict.fromkeys(
            EVENTS), seed
