"""WP-1026 — indexing acceptance against a **published, scored** benchmark.

Bergmann, Le Bail, Shirley & Zlokazov (2004), *Z. Kristallogr.* **219**, 783-790
ran eleven indexing programs over one compound at six levels of difficulty and
printed both the data (Table 6) and every program's score (Table 5).  No other
feature in this package has had that: the bar here is not a tolerance somebody
chose, it is what ITO13, DICVOL91, TREOR90 and McMaille actually achieved on
these exact numbers.

Three groups of tests, and the order is deliberate.

**First the fixture proves itself.**  Two hundred numbers were typed from a
printed table, so before anything is graded against them they are checked against
three statements the paper makes *in prose and never tabulates* — the zeroshift
arithmetic, the I ≥ 5 % subsetting, and its own impurity counts.  A transcription
error breaks at least one.

**Then the claims that need no search**, which is where the strongest evidence
is: the published figures of merit, and the first test of the paper's own
hypothesis about what caused the zeroshift.

**Then the search itself**, marked ``slow``.

**The global score is deliberately absent from this file, and it is generated
rather than unmeasured.**  It lives in ``tests/bethanechol_benchmark.py``, a
module you *run* — ``python -m tests.bethanechol_benchmark`` — because the
paper's protocol is ten sets × two modes × three engines with the default mode
searching all seven crystal systems, tens of minutes of pure search for a number
that moves only when an engine moves.  A ``slow`` row that size would sit on the
weekly job's critical path (``tests/CLAUDE.md`` § *One dataset, one group*).
What this file keeps is the half that is cheap and does not decay: the
transcription checks above, and fast rows pinning the **scoring rule** and the
**lattice match** the runner grades with, which are where a benchmark harness
actually goes wrong.

Two earlier statements in this docstring were withdrawn, and the second is worth
knowing before adding any row that quotes a search:

- *"Every engine exhausts its budget without finishing that domain — 0
  candidates at 240 s, still 0 in manual mode at 900 s, so the honest report is
  silence."*  **There is no silence**: every run returns twelve candidates
  (WP-1043, re-measured on the merged tree).  The claim was made once in July
  and carried verbatim through four WPs that all touched the engines.
- *"F is the only one of the ten we solve."*  On the tree that reopened WP-1026,
  **E is solved too**, and both are the truth at **rank 1** — the point being
  that neither sentence was regenerated by anything.  Which is the whole reason
  the score is a runner and this docstring is not the record.

An incomplete search still says nothing at all (``EngineResult.search_complete``,
False on every monoclinic run here), so the runner reports it beside every score
rather than scoring the clock.

One protocol note, because it decides whether any of this means anything: the
sets arrive as bare positions, so every one of them is a ``from_positions`` list
whose σ is *assumed*.  That is the input the benchmark defines, and it is why
``PEAK_SIGMA_ASSUMED`` fires on all ten and why none of them may be refused on a
precision figure computed from that σ (``indexing/quality.py``).

The convergence schedule these rankings were produced under is the package
default (``intermediate_ftol``, WP-1123), inherited deliberately: the plan the
validation fit runs is ``indexing.workflow.validation_plan``, which declares it
there with the reason, and a ranking is only worth pinning if it is the ranking
a caller actually gets.
"""

